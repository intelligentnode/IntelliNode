// Embeds resource/templates/*.in into a JS module so the prompt templates also load in the browser bundle.
const fs = require('fs');
const path = require('path');

const templatesDir = path.join(__dirname, '..', 'resource', 'templates');
const templates = {};
for (const file of fs.readdirSync(templatesDir).filter((name) => name.endsWith('.in')).sort()) {
  templates[file] = fs.readFileSync(path.join(templatesDir, file), 'utf8');
}

const output = '// Generated by scripts/build-templates.js from resource/templates/*.in - do not edit.\n'
  + `module.exports = ${JSON.stringify(templates, null, 2)};\n`;
fs.writeFileSync(path.join(templatesDir, 'templates.js'), output);
console.log(`Embedded ${Object.keys(templates).length} prompt templates`);
